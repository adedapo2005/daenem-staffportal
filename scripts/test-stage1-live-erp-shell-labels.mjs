import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { labelForAuthenticatedWorkspace, correctLiveErpShellLabels } from '../src/stage1-live-erp-shell-labels.ts';
assert.equal(labelForAuthenticatedWorkspace('Owner · Demo Session','session'),'Owner · Authenticated Session');
assert.equal(labelForAuthenticatedWorkspace('Manager · Demo Session','session'),'Manager · Authenticated Session');
assert.equal(labelForAuthenticatedWorkspace('Owner · Authenticated Session','session'),'Owner · Authenticated Session');
assert.equal(labelForAuthenticatedWorkspace('Demo Environment · Daenem Executive Command','environment'),'Pre-Production · Daenem Executive Command');
assert.equal(labelForAuthenticatedWorkspace('Production · Main','environment'),'Production · Main');
const nav={textContent:'Owner · Demo Session'};
const foot={textContent:'Demo Environment · Daenem Executive Command'};
const root={querySelector:(selector)=>selector==='.p-user-card small'?nav:selector==='.p-footer > span:nth-child(2)'?foot:null};
const restore=correctLiveErpShellLabels(root);
assert.equal(nav.textContent,'Owner · Authenticated Session');
assert.equal(foot.textContent,'Pre-Production · Daenem Executive Command');
restore();
assert.equal(nav.textContent,'Owner · Demo Session');
assert.equal(foot.textContent,'Demo Environment · Daenem Executive Command');
const restore2=correctLiveErpShellLabels(root);
nav.textContent='Other session changed';
restore2();
assert.equal(nav.textContent,'Other session changed');
assert.equal(foot.textContent,'Demo Environment · Daenem Executive Command');
const bridge=readFileSync(new URL('../src/stage1-live-erp-route-bridge.tsx',import.meta.url),'utf8');
const source=readFileSync(new URL('../source-snapshots/DAENEM-StaffPortal-Post-SignIn-v115/app/experience/Portal.tsx',import.meta.url),'utf8');
assert.match(bridge,/correctLiveErpShellLabels\(root\)/);
assert.match(bridge,/if \(!route \|\| !mount\) return/);
assert.match(source,/Demo Environment/);
console.log('Live ERP authenticated shell label contracts passed (15 checks).');
