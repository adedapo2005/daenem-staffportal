import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from '../node_modules/typescript/lib/typescript.js';

const raw=fs.readFileSync(new URL('../src/bakery-intelligence-metrics.ts',import.meta.url),'utf8');
const transpiled=ts.transpileModule(raw,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const {compareMetric,bakeryPeriodComparison}=await import('data:text/javascript;base64,'+Buffer.from(transpiled).toString('base64'));
assert.deepEqual(compareMetric(120,100),{current:120,previous:100,absolute:20,percentage:20});
assert.deepEqual(compareMetric(0,0),{current:0,previous:0,absolute:0,percentage:null});
assert.deepEqual(compareMetric(50,0),{current:50,previous:0,absolute:50,percentage:null});
assert.deepEqual(compareMetric(30,60),{current:30,previous:60,absolute:-30,percentage:-50});
const production=Array.from({length:14},(_,i)=>({day:`2026-10-${String(i+1).padStart(2,'0')}`,goodLoaves:i<7?100:120,productionLossLoaves:i<7?10:5,completedBatches:i<7?1:2}));
const orders=Array.from({length:14},(_,i)=>({day:production[i].day,orders:i<7?2:3,orderValueKobo:i<7?100000:120000,recordedOrderPaymentsKobo:0}));
const history={periodStart:production[0].day,periodEnd:production[13].day,timeZone:'Africa/Lagos',source:'test fixture only',production,orders};
const result=bakeryPeriodComparison(history);
assert.equal(result.output.current,840);
assert.equal(result.output.previous,700);
assert.equal(result.output.absolute,140);
assert.equal(result.output.percentage,20);
assert.equal(result.productionLoss.current,35);
assert.equal(result.productionLoss.previous,70);
assert.equal(result.productionLoss.absolute,-35);
assert.equal(result.productionLoss.percentage,-50);
assert.equal(result.completedBatches.absolute,7);
assert.equal(result.lossRate.current,4);
assert.equal(result.lossRate.points,-5.1);
assert.equal(result.commercial.orderValue.absolute,140000);
assert.equal(result.commercial.orderValue.percentage,20);
assert.equal(result.commercial.orderCount.absolute,7);
assert.equal(result.includesPartialToday,true);
assert.equal(bakeryPeriodComparison({...history,orders:null}).commercial,null);
assert.equal(bakeryPeriodComparison({...history,orders:orders.map((r,i)=>i===2?{...r,day:'2026-09-29'}:r)}).commercial,null);
assert.equal(bakeryPeriodComparison({...history,production:[...production].reverse()}),null);
assert.equal(bakeryPeriodComparison({...history,production:production.slice(0,13)}),null);
assert.equal(bakeryPeriodComparison({...history,production:production.map((r,i)=>i===1?{...r,day:production[0].day}:r)}),null);
assert.equal(bakeryPeriodComparison({...history,production:production.map((r,i)=>i===5?{...r,goodLoaves:-1}:r)}),null);
const zero=production.map((r,i)=>({...r,goodLoaves:i<7?0:50,productionLossLoaves:0}));
assert.equal(bakeryPeriodComparison({...history,production:zero}).output.percentage,null);
assert.equal(bakeryPeriodComparison({...history,production:zero}).lossRate.previous,null);
console.log('PASS Bakery 7-day comparisons: absolute, relative, zero baseline, waste-rate pp, permissions, bad rows and partial today');
