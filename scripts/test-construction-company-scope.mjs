import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const source = await readFile(new URL('../worker/construction.ts', import.meta.url), 'utf8');
const section = (name, next) => source.slice(source.indexOf(`async function ${name}(`), source.indexOf(`async function ${next}(`));
assert.match(source, /const can=\(c:SessionContext,l:[^;]*owner\(c\)\|\|!!companyId&&c\.companies\.some\(x=>x\.id===companyId\)&&hasPermission\(c,'construction\.access',l,companyId\)/);
assert.match(source, /hasPermission\(c,'construction\.access',l,companyId\)/, 'non-owner checks must use the target company permission map');
const overview = section('overview', 'listProjects');
assert.match(overview, /companyAllowed\(c,requested\)/);
assert.match(overview, /visibleCompanyIds\(c\)/);
assert.match(overview, /company_id IN \(\$\{ids\.map\(\(\)=>'\?'\)/);
const list = section('listProjects', 'createProject');
assert.match(list, /companyAllowed\(c,companyId\)/);
assert.match(list, /visibleCompanyIds\(c\)/);
assert.match(list, /cp\.company_id IN/);
const create = section('createProject', 'detail');
assert.match(create, /companyAllowed\(c,companyId,'create'\)/);
const detail = section('detail', 'const evidenceSources');
assert.ok(detail.indexOf('SELECT company_id companyId FROM construction_projects') < detail.indexOf('SELECT cp.*'), 'project company must be resolved and authorized before detail disclosure');
assert.match(detail, /!scope\|\|!companyAllowed\(c,scope\.companyId\)/);
const upload = section('uploadEvidence', 'listEvidence');
assert.match(upload, /companyAllowed\(c,project\.companyId,'edit'\)/);
assert.ok(upload.indexOf('companyAllowed') < upload.indexOf('env.FILES.put'), 'upload must authorize target-company edit before storage writes');
const evidenceList = section('listEvidence', 'streamEvidence');
assert.match(evidenceList, /companyAllowed\(c,project\.companyId\)/);
const stream = section('streamEvidence', 'child');
assert.match(stream, /companyAllowed\(c,scope\.companyId\)/);
assert.ok(stream.indexOf('companyAllowed') < stream.indexOf('SELECT e.r2_key'), 'file metadata must be fetched after target-company authorization');
assert.match(stream, /Evidence not found\./);
const child = source.slice(source.indexOf('async function child('), source.indexOf('export async function routeConstruction'));
assert.match(child, /companyAllowed\(c,p\.companyId,'edit'\)/);
assert.ok(child.indexOf('companyAllowed') < child.indexOf('INSERT INTO construction_'), 'child writes must be authorized against resolved project company');
console.log('Construction target-company authorization: 18 assertions PASS');
