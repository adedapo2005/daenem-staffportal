import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

const source = await readFile(new URL('../worker/communications-service.ts', import.meta.url), 'utf8');
const mutations = await readFile(new URL('../worker/weather-credential-mutations.ts', import.meta.url), 'utf8');
const start = source.indexOf('async function weatherCredentialSetting');
const end = source.indexOf('\nasync function getPolicy', start);
const endpoint = source.slice(start, end);
const testFlowStart = mutations.indexOf('export async function runGoogleWeatherProviderTestWithAudit');
const testFlowEnd = mutations.indexOf('\nfunction requiredAuditGuard', testFlowStart);
const testFlow = mutations.slice(testFlowStart, testFlowEnd);
assert.ok(start >= 0 && end > start);
assert.ok(testFlowStart >= 0 && testFlowEnd > testFlowStart);
assert.match(endpoint, /if\(!owner\(context\)\).*403/);
assert.match(endpoint, /weather-credential\/test/);
assert.match(endpoint, /if\(!body\|\|typeof body!=='object'\|\|Array\.isArray\(body\)\).*Invalid weather test request/s);
assert.match(endpoint, /env\.APP_STAGE==='production'/);
assert.match(endpoint, /typeof body\.latitude!=='number'\|\|typeof body\.longitude!=='number'/);
assert.match(endpoint, /latitude < -90\|\|latitude > 90/);
assert.match(endpoint, /longitude < -180\|\|longitude > 180/);
assert.match(endpoint, /runGoogleWeatherProviderTestWithAudit\(env,context\.employee\.id,\(\)=>uid\('audit'\)/);
assert.match(endpoint, /readGoogleWeather\(env,latitude,longitude,'IMPERIAL',true\)/);
assert.match(endpoint, /Weather provider test could not be fully audited\./);
assert.ok(testFlow.indexOf("phase: 'started'") < testFlow.indexOf('testProvider()'), 'persist test intent before the provider request');
assert.ok(testFlow.indexOf('testProvider()') < testFlow.indexOf("phase: 'completed'"), 'persist provider result after the request');
assert.match(testFlow, /recordGoogleWeatherProviderTestWithAudit/);
assert.doesNotMatch(endpoint, /JSON\.stringify\(.*latitude|JSON\.stringify\(.*longitude/s);
assert.match(mutations, /Number\(result\.meta\?\.changes \|\| 0\) !== 1/);
assert.match(source, /weather-credential\/test/);
console.log('Google Weather non-production provider connection and audit boundary: PASS');
