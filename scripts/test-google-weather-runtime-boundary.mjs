import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

const source = await readFile(new URL('../worker/index.ts', import.meta.url), 'utf8');
const profile = await readFile(new URL('../worker/profile-management.ts', import.meta.url), 'utf8');
const provider = await readFile(new URL('../worker/weather-provider.ts', import.meta.url), 'utf8');
const start = source.indexOf('async function weather(');
const end = source.indexOf('\n\nasync function readPublicSignInConfig', start);
const endpoint = source.slice(start, end);
assert.match(source, /getSessionContext\(request, env\)[\s\S]*?if \(url\.pathname === '\/api\/context\/weather'[\s\S]*?weather\(request, env\)/);
assert.match(endpoint, /WEATHER_PROVIDER_ENABLED !== 'true'/);
assert.match(endpoint, /APP_STAGE === 'production'/);
assert.match(endpoint, /readGoogleWeather\(env, lat, lon\)/);
assert.match(endpoint, /providerStatus: result\.providerStatus/);
assert.match(endpoint, /result\.providerStatus === 'provider_required' \? 200 : 502/);
assert.match(provider, /resolveMetaCredential\(env, 'google_weather_api_key'\)/);
assert.match(provider, /!Number\.isFinite\(latitude\) \|\| latitude < -90 \|\| latitude > 90/);
assert.match(provider, /!Number\.isFinite\(longitude\) \|\| longitude < -180 \|\| longitude > 180/);
assert.match(provider, /unitsSystem !== 'IMPERIAL' && unitsSystem !== 'METRIC'/);
assert.ok(provider.indexOf('Invalid values must not become cache keys or provider requests.') < provider.indexOf('const cache = env.SOCIAL_CACHE;'));
assert.match(provider, /https:\/\/weather\.googleapis\.com\/v1\/currentConditions:lookup/);
assert.match(provider, /headers: \{ 'X-Goog-Api-Key': key \}/);
assert.match(provider, /const PROVIDER_TIMEOUT_MS = 8_000/);
assert.match(provider, /signal: AbortSignal\.timeout\(PROVIDER_TIMEOUT_MS\)/);
assert.doesNotMatch(provider, /searchParams\.set\(['"]key['"]/);
assert.match(provider, /expirationTtl: CACHE_TTL_SECONDS/);
assert.match(provider, /const CACHE_TTL_SECONDS = 300/);
assert.match(provider, /const inFlightWeather = new Map<string, Promise<GoogleWeatherResult>>\(\)/);
assert.match(provider, /const existingRequest = inFlightWeather\.get\(cacheKey\)/);
assert.match(provider, /if \(existingRequest\) return existingRequest/);
assert.match(provider, /inFlightWeather\.set\(cacheKey, request\)/);
assert.match(provider, /inFlightWeather\.get\(cacheKey\) === request\) inFlightWeather\.delete\(cacheKey\)/);
assert.match(provider, /fetchAndCacheWeather\(env, latitude, longitude, unitsSystem, cacheKey, cache\)/);
assert.match(provider, /weather:google:v1:\$\{digestHex\}/);
assert.match(provider, /cache\.get\(cacheKey\)/);
assert.match(provider, /cache\.put\(cacheKey, value/);
assert.match(provider, /providerStatus: 'cached'/);
assert.match(provider, /providerStatus: 'provider_required'/);
assert.doesNotMatch(provider, /console\.(log|warn|error)|X-Goog-Api-Key.*cache\.put/);
assert.match(endpoint, /Math\.abs\(lat\) > 90 \|\| Math\.abs\(lon\) > 180/);
assert.match(endpoint, /rawLat === null \|\| rawLon === null \|\| !rawLat\.trim\(\) \|\| !rawLon\.trim\(\)/);
assert.match(endpoint, /providerStatus: 'provider_required'/);
assert.doesNotMatch(endpoint, /open-meteo|apiKey|credentialKey/);
assert.doesNotMatch(source, /api\.open-meteo\.com/);
assert.match(profile, /readGoogleWeather\(env,place\.latitude!,place\.longitude!\)/);
assert.match(profile, /providerStatus:'provider_required'/);
assert.match(profile, /Math\\.abs\\(place\\.latitude!\\)>90\\|\\|Math\\.abs\\(place\\.longitude!\\)>180/);
assert.doesNotMatch(profile, /open-meteo|weatherText/);
